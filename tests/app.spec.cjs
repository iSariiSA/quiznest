const {test,expect,_electron:electron}=require('@playwright/test');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
let app,page,directory;
const outputs=process.env.QUIZNET_SCREENSHOTS || path.resolve(__dirname,'../test-results/screenshots');
async function launch(){const env={...process.env,QUIZNET_TEST_DATA:directory};delete env.ELECTRON_RUN_AS_NODE;app=await electron.launch({executablePath:process.env.QUIZNET_ELECTRON_PATH||undefined,args:[path.resolve(__dirname,'..')],env});page=await app.firstWindow();await expect(page.locator('.brand')).toBeVisible();}
test.beforeAll(async()=>{directory=await fs.mkdtemp(path.join(os.tmpdir(),'quiznet-app-'));await launch();});
test.afterAll(async()=>{await app?.close();await fs.rm(directory,{recursive:true,force:true});});
test('real desktop workflow: hierarchy, scoring, resume, import/export and backup',async()=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await fs.mkdir(outputs,{recursive:true});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setBounds({width:1360,height:980}));
  await expect(page.locator('.course-card')).toHaveCount(3);
  await page.screenshot({path:path.join(outputs,'Quiznet-library.png')});
  await page.locator('.course-card').filter({hasText:'Biology'}).click();
  await expect(page.locator('.unit-section')).toHaveCount(2);
  await page.screenshot({path:path.join(outputs,'Quiznet-course.png')});
  await page.locator('.quiz-row').first().getByRole('button',{name:'Start quiz'}).click();
  await page.getByRole('button',{name:'Begin quiz'}).click();
  await page.locator('[data-action="answer"][data-index="1"]').click();
  await expect(page.locator('.answer-option.chosen')).toHaveCount(1);
  await page.screenshot({path:path.join(outputs,'Quiznet-quiz.png')});
  await page.getByRole('button',{name:'Next question'}).click();
  await page.locator('[data-action="answer"][data-index="0"]').click();
  await expect(page.locator('.quiz-title-row>span')).toHaveText('2 / 5 answered');
  await app.close();await launch();
  await expect(page.locator('.resume-banner')).toBeVisible();
  await page.getByRole('button',{name:'Pick up where you left off'}).click();
  await expect(page.locator('.answer-option.chosen')).toHaveCount(1);
  await page.getByRole('button',{name:'Next question'}).click();
  await page.locator('[data-action="answer"][data-index="2"]').click();
  await page.getByRole('button',{name:'Next question'}).click();
  await page.locator('[data-action="answer"][data-index="1"]').click();
  await page.getByRole('button',{name:'Next question'}).click();
  await page.getByRole('button',{name:'Finish quiz'}).click();
  await expect(page.locator('#toast')).toContainText('Answer every question');
  await page.locator('[data-action="answer"][data-index="0"]').click();
  await page.getByRole('button',{name:'Finish quiz'}).click();
  await expect(page.locator('.score-medallion>span')).toContainText('80');
  await expect(page.locator('.review-badge.wrong')).toHaveCount(1);
  await expect(page.locator('.review-list')).toContainText('The nucleus');
  await page.screenshot({path:path.join(outputs,'Quiznet-results.png')});
  await page.getByRole('button',{name:'Back to library'}).click();
  // Create an entire course and a quiz through the actual editor.
  await page.getByRole('button',{name:'New course',exact:true}).last().click();
  await page.getByLabel('Course name').fill('Physics');await page.getByRole('button',{name:'Create course',exact:true}).click();
  await page.getByRole('button',{name:'New unit',exact:true}).click();
  await page.getByLabel('Unit name').fill('Unit 1: Waves');await page.getByRole('button',{name:'Create unit',exact:true}).click();
  await page.getByRole('button',{name:'New quiz',exact:true}).click();
  await page.getByLabel('Quiz title').fill('Wave basics');
  await page.locator('[data-editor="prompt"]').fill('What travels in a vacuum?');
  for(const [i,text] of ['Light','Sound','Water','Air'].entries())await page.locator(`[data-editor="option"][data-option="${i}"]`).fill(text);
  await page.locator('[data-editor="explanation"]').fill('Electromagnetic waves can travel in a vacuum.');
  await page.getByRole('button',{name:'Save quiz',exact:true}).click();await expect(page.locator('.quiz-info')).toContainText('Wave basics');
  // Native file pickers are stubbed; parsing, disk I/O, preview and confirmation are real.
  const importPath=path.resolve(__dirname,'../examples/biology.json');
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},importPath);
  await page.getByRole('button',{name:'Import questions'}).click();
  await expect(page.locator('.import-preview')).toContainText('Quiz 1');
  await page.locator('#import-target').selectOption('');
  await page.getByRole('button',{name:'Import quizzes',exact:true}).click();
  await expect(page.locator('.course-card')).toHaveCount(4);
  const backup=path.join(directory,'exported-backup.json');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},backup);
  await page.getByRole('button',{name:'Settings & backups'}).click();await page.getByRole('button',{name:'Save a backup',exact:true}).click();
  await expect(page.locator('#toast')).toContainText('backup is saved');
  const saved=JSON.parse(await fs.readFile(backup,'utf8'));expect(saved.courses).toHaveLength(4);expect(saved.attempts).toHaveLength(1);
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},backup);
  await page.getByRole('button',{name:'Choose backup'}).click();await page.getByRole('button',{name:'Restore library',exact:true}).click();
  await expect(page.locator('.course-card')).toHaveCount(4);
  expect((await fs.readdir(path.join(directory,'data'))).some(f=>f.startsWith('before-restore-'))).toBeTruthy();
  // No renderer network connectivity; imported markup stays plain text.
  const blocked=await page.evaluate(async()=>{try{await fetch('https://example.com');return false;}catch{return true;}});expect(blocked).toBe(true);
  expect(errors).toEqual([]);
});
