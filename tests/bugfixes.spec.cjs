const {test,expect,_electron:electron}=require('@playwright/test');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
let app,page,directory,clipboardText;
test.beforeEach(async()=>{
  directory=await fs.mkdtemp(path.join(os.tmpdir(),'quiznet-bugfixes-'));
  const env={...process.env,QUIZNET_TEST_DATA:directory};delete env.ELECTRON_RUN_AS_NODE;
  app=await electron.launch({executablePath:process.env.QUIZNET_ELECTRON_PATH||undefined,args:[path.resolve(__dirname,'..')],env});
  page=await app.firstWindow();await expect(page.locator('.brand')).toBeVisible();
  clipboardText=await app.evaluate(({clipboard})=>clipboard.readText());
});
test.afterEach(async()=>{
  if(app){await app.evaluate(({clipboard},value)=>clipboard.writeText(value),clipboardText||'');await app.close();}
  const resolved=path.resolve(directory);if(!resolved.startsWith(path.resolve(os.tmpdir())+path.sep)||!path.basename(resolved).startsWith('quiznet-bugfixes-'))throw new Error('Unexpected test directory');
  await fs.rm(resolved,{recursive:true,force:true});
});
test('exact question mixes update the total when counts and included types change',async()=>{
  await page.getByRole('button',{name:'Prepare a quiz',exact:true}).click();
  await page.getByLabel('Question types',{exact:true}).selectOption('value');
  await page.getByLabel('Multiple answers',{exact:true}).selectOption('omit');
  await page.getByLabel('True / false',{exact:true}).selectOption('omit');
  await page.getByLabel('Multiple choice (one answer)',{exact:true}).selectOption('value');
  await page.getByLabel('Multiple choice (one answer) count',{exact:true}).fill('5');
  await expect(page.getByLabel('Number of questions value',{exact:true})).toHaveValue('5');
  await page.getByLabel('Multiple answers',{exact:true}).selectOption('value');
  await page.getByLabel('Multiple answers count',{exact:true}).fill('10');
  await expect(page.getByLabel('Number of questions value',{exact:true})).toHaveValue('15');
  await page.getByLabel('Multiple choice (one answer) count',{exact:true}).fill('7');
  await expect(page.getByLabel('Number of questions value',{exact:true})).toHaveValue('17');
  await page.getByLabel('Multiple answers',{exact:true}).selectOption('omit');
  await expect(page.getByLabel('Number of questions value',{exact:true})).toHaveValue('7');
  await page.getByRole('button',{name:'Copy instructions',exact:true}).click();
  await expect.poll(()=>app.evaluate(({clipboard})=>clipboard.readText())).toContain('- Number of questions: 7');
  const before=await fs.readFile(path.join(directory,'data/library.json'),'utf8');
  await page.getByRole('button',{name:'History',exact:true}).click();
  await page.getByRole('button',{name:'App menu'}).click();await page.getByRole('menuitem',{name:'Prepare a quiz…',exact:true}).click();
  await expect(page.getByLabel('Number of questions value',{exact:true})).toHaveValue('7');
  await page.getByLabel('Multiple answers',{exact:true}).selectOption('auto');
  await expect(page.getByLabel('Number of questions value',{exact:true})).toHaveValue('8');
  await expect(page.locator('.instruction-count-summary')).toContainText('Mix minimum: 8 questions');
  await page.getByLabel('Number of questions',{exact:true}).selectOption('ask');
  await page.getByLabel('Multiple answers',{exact:true}).selectOption('omit');
  await page.getByLabel('Multiple choice (one answer) count',{exact:true}).fill('9');
  await expect(page.getByLabel('Number of questions',{exact:true})).toHaveValue('ask');
  await page.getByRole('button',{name:'Copy instructions',exact:true}).click();
  await expect.poll(()=>app.evaluate(({clipboard})=>clipboard.readText())).toContain('- Number of questions: Ask the user');
  await page.getByLabel('Number of questions',{exact:true}).selectOption('auto');
  await page.getByLabel('Multiple choice (one answer) count',{exact:true}).fill('7');
  expect(await fs.readFile(path.join(directory,'data/library.json'),'utf8')).toBe(before);
});
test('disabling code clears its dependent language setting and allows instruction export',async()=>{
  await page.getByRole('button',{name:'Prepare a quiz',exact:true}).click();
  await page.locator('.instruction-advanced summary').click();
  await page.getByLabel('Code questions',{exact:true}).selectOption('required');
  await page.getByLabel('Code language',{exact:true}).selectOption('value');
  await page.getByLabel('Code language value',{exact:true}).fill('Python');
  await page.getByLabel('Code questions',{exact:true}).selectOption('none');
  await expect(page.getByLabel('Code language',{exact:true})).toHaveValue('auto');
  await expect(page.getByLabel('Code language',{exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'Copy instructions',exact:true}).click();
  await expect(page.locator('.instruction-error')).toBeEmpty();
  await expect.poll(()=>app.evaluate(({clipboard})=>clipboard.readText())).toContain('- Code questions: No code');
  await page.getByRole('button',{name:'History',exact:true}).click();
  await page.getByRole('button',{name:'App menu'}).click();await page.getByRole('menuitem',{name:'Prepare a quiz…',exact:true}).click();
  await page.locator('.instruction-advanced summary').click();
  await expect(page.getByLabel('Code language',{exact:true})).toBeDisabled();
  await page.getByLabel('Code questions',{exact:true}).selectOption('relevant');
  await expect(page.getByLabel('Code language',{exact:true})).toBeEnabled();
  await page.getByLabel('Code language',{exact:true}).selectOption('ask');
  await page.getByLabel('Code questions',{exact:true}).selectOption('none');
  await page.getByRole('button',{name:'Preview',exact:true}).click();
  expect(await page.getByLabel('Markdown instructions',{exact:true}).inputValue()).toContain('- Code language: Let the agent decide.');
});
